"""Live financial analysis shared with the management dashboard; no snapshots."""
from odoo import _, api, fields, models, tools
from odoo.exceptions import AccessError
from .dashboard_queries import FINANCIAL_ROWS


class FinancialAnalysis(models.Model):
    _name = 'fitzone.financial.analysis'
    _description = 'FitZone Financial Analysis'
    _auto = False
    _order = 'date desc, department_id'
    _rec_name = 'department_name'

    date = fields.Date(readonly=True)
    company_id = fields.Many2one('res.company', readonly=True)
    currency_id = fields.Many2one(related='company_id.currency_id')
    department_id = fields.Many2one('hr.department', readonly=True)
    department_name = fields.Char(readonly=True, string='Department name')
    revenue = fields.Monetary(readonly=True, string='Revenue (invoiced/accrual)')
    manual_expenses = fields.Monetary(readonly=True)
    purchase_expenses = fields.Monetary(readonly=True)
    total_expenses = fields.Monetary(readonly=True)
    net_revenue = fields.Monetary(readonly=True)

    def _check_access(self, operation):
        result = super()._check_access(operation)
        if not self.env.user.has_group('fitzone.group_fitzone_manager'):
            return self, lambda: AccessError(self.env._('Only FitZone Managers may access financial reports.'))
        return result

    def _search(self, domain, *args, **kwargs):
        if not self.env.user.has_group('fitzone.group_fitzone_manager'):
            raise AccessError(self.env._('Only FitZone Managers may access financial reports.'))
        return super()._search(domain, *args, **kwargs)

    @api.model
    def get_view(self, view_id=None, view_type='form', **options):
        if view_type == 'form':
            raise AccessError(_('Aggregate reports are available as lists, pivots and graphs.'))
        return super().get_view(view_id, view_type, **options)

    def init(self):
        """Tax-exclusive expenses = manual entries + posted vendor product lines.

        POs only allocate bill lines; unbilled POs never enter expenses. Refund
        balances reduce expense. POS linked to invoices is excluded from POS
        revenue. Manual expenses represent separate costs, never copies of bills;
        no manual record is generated by purchase or billing. Accounting balances
        are already in each company's currency at the accounting exchange rate.
        POS dates use the company contact timezone (UTC if unset), shared with
        the dashboard. Invoice dates remain their accounting calendar dates.
        """
        tools.drop_view_if_exists(self.env.cr, self._table)
        self.env.cr.execute('''CREATE VIEW fitzone_financial_analysis AS
            SELECT row_number() OVER (ORDER BY s.company_id,s.day,s.department)::integer AS id,
                s.company_id, s.day AS date, NULLIF(s.department,0) AS department_id,
                COALESCE(d.name->>'en_US','Unassigned') AS department_name,
                sum(s.revenue) AS revenue, sum(s.manual_expenses) AS manual_expenses,
                sum(s.purchase_expenses) AS purchase_expenses,
                sum(s.manual_expenses+s.purchase_expenses) AS total_expenses,
                sum(s.revenue-s.manual_expenses-s.purchase_expenses) AS net_revenue
            FROM (''' + FINANCIAL_ROWS + ''') s
            LEFT JOIN hr_department d ON d.id=s.department
            GROUP BY s.company_id,s.day,s.department,d.name''')
